# 这几行是"防乱码开关"，让中文和表情不乱码、不报错，先不用管它
import sys
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stdin.reconfigure(encoding="utf-8")
except Exception:
    pass

# print() 是"打印"的意思，把括号里的文字显示到屏幕上
print("Hello, Python!")

# 想说什么就写什么，记得文字要放在双引号 " " 里
print("你好，我是电脑！")

# 一行可以打印多个东西，用逗号隔开
print("我", "会", "说", "话", "了")

# 还能打印表情符号，让程序更可爱
print("今天也要加油鸭！🦆✨")

# 空一行：print() 什么都不写，就会打印一个空行
print()
print("你看，上面空了一行")

# 想在文字中间换行？用 \n
print("第一行\n第二行\n第三行")

# 电脑做自我介绍（用 print 拼出一个方框图案）
print("===========================")
print("|  嗨，我是 Python 小助手！|")
print("|  很高兴认识你~          |")
print("===========================")

# ---- 小彩蛋：让电脑叫出你的名字 ----
# input() 会停下来等你打字，下一课再详细学，今天先体验一下
name = input("对了，你叫什么名字呀？ ")
print("哇，" + name + "，这个名字真好听！")
print(name + "，从今天起你就是小程序员啦！🎉")
