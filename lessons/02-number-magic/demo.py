# 防乱码开关（先不用管）
import sys
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stdin.reconfigure(encoding="utf-8")
except Exception:
    pass

# ---------- 一、变量：贴了标签的小盒子 ----------
# 变量就像一个盒子，上面贴着名字，里面装着东西
# 用 = 号把东西"放进"盒子里
name = "小明"     # 名字是文字，要加双引号
coins = 100       # 金币是数字，不用加双引号

print(name, "有", coins, "个金币")

# ---------- 二、数字的四则运算 ----------
# 加 +   减 -   乘 *   除 /
print("100 + 30 =", 100 + 30)
print("100 - 20 =", 100 - 20)
print("100 * 3  =", 100 * 3)
print("100 / 4  =", 100 / 4)   # 除法结果会带小数点，25.0 就是 25

# 变量也能参与计算
coins = coins + 50      # 打怪又赚了 50 个金币
print("打怪后，金币变成", coins, "个")

# ---------- 三、input()：让程序"听"你说话 ----------
# input() 会停下来等你打字，把你打的字当成"文字"还给你
# 重点：input() 拿到的永远是"文字"，要算数得先用 int() 变成数字
print()
text_a = input("请输入第一个数字：")
text_b = input("请输入第二个数字：")

print("直接相加（还是文字）：", text_a + text_b)              # 会拼在一起！
print("用 int() 变成数字再相加：", int(text_a) + int(text_b))  # 这才是真正的加法

# ---------- 四、小计算器：算零花钱 ----------
print()
print("=== 零花钱小计算器 ===")
money = int(input("你这个月有多少零花钱？"))
cost  = int(input("你想买的东西多少钱？"))
left  = money - cost
print("买完后你还剩", left, "元")
print("如果每个月都剩", left, "元，存一年就有", left * 12, "元！")
