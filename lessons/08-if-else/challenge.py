# 防乱码开关（先不用管）
import sys
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stdin.reconfigure(encoding="utf-8")
except Exception:
    pass

print("奇偶数判断器！")

n = int(input("输入一个整数："))

if n % 2 == 0:          # 能被 2 整除 = 偶数（第 5 课的 % 又用上了）
    print(n, "是偶数")
else:
    print(n, "是奇数")

