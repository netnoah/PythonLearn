# 防乱码开关（先不用管）
import sys
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stdin.reconfigure(encoding="utf-8")
except Exception:
    pass

print("天气穿衣小助手！")

temp = int(input("今天几度？（摄氏度）："))

if temp >= 30:
    print("太热啦！穿短袖 + 短裤 🩳")
elif temp >= 20:
    print("温暖，穿长袖或薄外套 👕")
elif temp >= 10:
    print("有点凉，穿外套 🧥")
elif temp >= 0:
    print("冷！穿棉袄，戴围巾 🧣")
else:
    print("冻死啦！裹成粽子 🥶")

