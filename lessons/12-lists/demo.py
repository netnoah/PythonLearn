# 防乱码开关（先不用管）
import sys
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stdin.reconfigure(encoding="utf-8")
except Exception:
    pass

print("藏宝箱！")

# ============================================
# 新本领：list（列表）
#   用 [ ] 把很多东西装在一起，按顺序排好
# ============================================

# ---------- 1. 创建一个列表：游戏背包 ----------
backpack = ["剑", "盾牌", "药水", "金币"]
print("我的背包：", backpack)

# ---------- 2. 用编号取东西（编号从 0 开始！）----------
print("第 1 样（编号 0）：", backpack[0])
print("第 2 样（编号 1）：", backpack[1])
print("第 3 样（编号 2）：", backpack[2])

# ---------- 3. 数一数有几样：len() ----------
print("背包里一共有", len(backpack), "样东西")

# ---------- 4. 装新东西：append() ----------
backpack.append("弓箭")
print("捡到弓箭！现在：", backpack)
print("背包里一共有", len(backpack), "样东西")

# ---------- 5. 按编号换掉：直接赋值 ----------
backpack[0] = "火焰剑"      # 把"剑"升级成"火焰剑"
print("剑升级了！现在：", backpack)

# ---------- 6. 小彩蛋：编号 -1 是最后一个 ----------
print("最后一样（编号 -1）：", backpack[-1])
